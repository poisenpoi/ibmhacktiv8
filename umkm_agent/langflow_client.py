from __future__ import annotations

import json
import os
import urllib.request
import urllib.error
from typing import Any, Dict, Optional, Tuple

# ── Konfigurasi (dari env, TIDAK dari hardcode) ─────────────────────────────
LANGFLOW_URL     = os.environ.get("LANGFLOW_URL", "http://127.0.0.1:7860").rstrip("/")
# LANGFLOW_API_KEY: nilai env saat module-load (digunakan cek api_key_set di check_status).
# Runtime key-lookup dilakukan di _headers() agar file dapat diganti tanpa restart.
LANGFLOW_API_KEY = os.environ.get("LANGFLOW_API_KEY", "")
UMKM_FLOW_ID     = os.environ.get("UMKM_FLOW_ID", "")   # diisi setelah import flow


class LangflowError(Exception):
    """Error dari Langflow API."""
    def __init__(self, msg: str, status: int = 0):
        super().__init__(msg)
        self.status = status


def _read_api_key_file() -> str:
    """
    Baca API key dari file path di env LANGFLOW_API_KEY_FILE.
    Return string key (stripped), atau "" jika file tidak ada/error.
    TIDAK pernah mencetak/log nilai key.
    """
    key_file = os.environ.get("LANGFLOW_API_KEY_FILE", "").strip()
    if not key_file:
        return ""
    try:
        with open(key_file, "r", encoding="utf-8") as f:
            return f.readline().strip()
    except (FileNotFoundError, PermissionError, OSError) as e:
        import sys
        print(f"[umkm_agent] PERINGATAN: Tidak bisa baca LANGFLOW_API_KEY_FILE: {e}",
              file=sys.stderr)
        return ""


def _headers() -> Dict[str, str]:
    """
    Build HTTP headers. API key resolved at call time:
      1. env LANGFLOW_API_KEY jika non-empty (precedence)
      2. file LANGFLOW_API_KEY_FILE dibaca tiap kali (agar key baru efektif tanpa restart)
    """
    h = {"Content-Type": "application/json", "Accept": "application/json"}
    key = os.environ.get("LANGFLOW_API_KEY", "").strip() or _read_api_key_file()
    if key:
        h["x-api-key"] = key
    return h


def _http_get(path: str, timeout: int = 10) -> Tuple[int, Any]:
    url = LANGFLOW_URL + path
    req = urllib.request.Request(url, headers=_headers())
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.status, json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8", errors="replace")
        return e.code, {"error": e.reason, "body": body[:500]}
    except Exception as e:
        return 0, {"error": str(e)}


def _http_post(path: str, payload: dict, timeout: int = 60) -> Tuple[int, Any]:
    url = LANGFLOW_URL + path
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(url, data=data, headers=_headers(), method="POST")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.status, json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8", errors="replace")
        return e.code, {"error": e.reason, "body": body[:500]}
    except Exception as e:
        return 0, {"error": str(e)}


def check_health() -> bool:
    """True jika Langflow dapat dijangkau."""
    status, _ = _http_get("/api/v1/version")
    return status == 200


def get_version() -> Optional[str]:
    """Kembalikan versi Langflow atau None."""
    status, data = _http_get("/api/v1/version")
    if status == 200 and isinstance(data, dict):
        return data.get("version")
    return None


def run_flow(
    teks_pesanan: str,
    flow_id: Optional[str] = None,
    input_component_id: Optional[str] = None,
    session_id: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Jalankan flow Langflow dengan input teks pesanan.
    
    Args:
        teks_pesanan: Teks mentah pesanan dari user.
        flow_id: ID flow (default dari UMKM_FLOW_ID env).
        input_component_id: ID komponen ChatInput (opsional untuk tweaks).
        session_id: Session ID untuk konteks percakapan (opsional).
    
    Returns:
        Dict dengan keys: output_text, raw_response
    
    Raises:
        LangflowError: jika Langflow tidak reachable atau mengembalikan error.
    """
    fid = flow_id or UMKM_FLOW_ID
    if not fid:
        raise LangflowError(
            "UMKM_FLOW_ID tidak diset. "
            "Import flows/asisten_pesanan_umkm.json melalui Langflow, lalu isi UMKM_FLOW_ID di .bob/mcp.json."
        )

    payload: Dict[str, Any] = {
        "input_value": teks_pesanan,
        "output_type": "chat",
        "input_type": "chat",
        "tweaks": {},
    }
    if session_id:
        payload["session_id"] = session_id

    status, data = _http_post(f"/api/v1/run/{fid}", payload, timeout=60)

    if status == 403:
        raise LangflowError(
            f"Langflow mengembalikan 403 Forbidden. "
            f"Set LANGFLOW_API_KEY env var dengan API key yang valid. "
            f"Buat API key di Langflow Settings → API Keys.",
            status=403,
        )

    if status != 200:
        raise LangflowError(
            f"Langflow run gagal: HTTP {status}. "
            f"Detail: {json.dumps(data)[:300]}",
            status=status,
        )

    # Ekstrak output text dari respons Langflow 1.12.0
    # Struktur: {"outputs": [{"outputs": [{"results": {"message": {"text": "..."}}}]}]}
    try:
        output_text = (
            data["outputs"][0]["outputs"][0]["results"]["message"]["text"]
        )
    except (KeyError, IndexError, TypeError):
        # Coba alternatif struktur
        try:
            output_text = data["outputs"][0]["outputs"][0]["artifacts"]["message"]
        except (KeyError, IndexError, TypeError):
            output_text = json.dumps(data)

    return {
        "output_text": output_text,
        "raw_response": data,
    }
