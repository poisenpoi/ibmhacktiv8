"""
umkm_agent/journal.py  — v2
Durable order journal berbasis SQLite (stdlib).
Generated by IBM Bob | Asisten Pesanan UMKM

Desain:
- doc_id / event_id   = ID live Google (hanya diisi jika LIVE mode)
- dry_doc_id / dry_event_id = ID dry-run (DRY://...), terpisah dari live
- Dry-run TIDAK mengisi kolom live; live tidak mengisi kolom dry
- Per-resource commit: update_commit_state dipanggil segera per-resource
- Idempoten: restart/retry aman — state persisten di DB
- Error disimpan di commit_error, TIDAK di catatan pelanggan
"""
from __future__ import annotations

import hashlib
import json
import os
import sqlite3
from datetime import datetime
from pathlib import Path
from typing import Optional
from zoneinfo import ZoneInfo

from .models import Order, OrderStatus

TZ_JKT = ZoneInfo("Asia/Jakarta")

_DEFAULT_DB = Path(os.environ.get(
    "UMKM_JOURNAL_DB",
    str(Path(__file__).parent.parent / ".journal" / "orders.db")
))


def _get_conn(db_path: Path = _DEFAULT_DB) -> sqlite3.Connection:
    db_path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(db_path), check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    return conn


def _init_db(conn: sqlite3.Connection) -> None:
    conn.executescript("""
        CREATE TABLE IF NOT EXISTS orders (
            order_id        TEXT PRIMARY KEY,
            revision        INTEGER NOT NULL DEFAULT 0,
            draft_hash      TEXT,
            status          TEXT NOT NULL,
            order_json      TEXT NOT NULL,
            teks_asli       TEXT,
            confirmed       INTEGER NOT NULL DEFAULT 0,

            -- Live Google resource IDs (HANYA diisi saat UMKM_GOOGLE_LIVE=1)
            doc_id          TEXT,
            doc_url         TEXT,
            doc_content_ok  INTEGER NOT NULL DEFAULT 0,
            event_id        TEXT,
            event_url       TEXT,

            -- Dry-run resource IDs (HANYA diisi saat dry-run, terpisah dari live)
            dry_doc_id      TEXT,
            dry_doc_url     TEXT,
            dry_event_id    TEXT,
            dry_event_url   TEXT,

            commit_error    TEXT,
            created_at      TEXT NOT NULL,
            updated_at      TEXT NOT NULL
        );
        CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);
    """)
    conn.commit()


def _order_id(order: Order) -> str:
    """Deterministic order ID dari teks asli + timestamp created_at."""
    seed = (order.teks_asli or "") + (
        order.dibuat_pada.isoformat() if order.dibuat_pada else ""
    )
    return "ORD-" + hashlib.sha256(seed.encode()).hexdigest()[:16].upper()


def _draft_hash(order: Order) -> str:
    """
    Hash konten draft untuk deteksi perubahan (stale-hash guard).
    Mencakup: nama_pelanggan, items (nama/jumlah/satuan/catatan_item),
              jatuh_tempo_dt, dan catatan order.
    Perubahan di SALAH SATU field ini → hash berubah → confirm_commit ditolak.
    """
    content = json.dumps({
        "nama":    order.nama_pelanggan,
        "items":   [
            {"n": i.nama, "q": i.jumlah, "s": i.satuan, "c": i.catatan_item}
            for i in order.items
        ],
        "jt":      order.jatuh_tempo_dt.isoformat() if order.jatuh_tempo_dt else None,
        "catatan": order.catatan,
    }, sort_keys=True)
    return hashlib.sha256(content.encode()).hexdigest()[:24]


def save_draft(order: Order, db_path: Path = _DEFAULT_DB) -> str:
    """
    Simpan draft order ke journal.
    Return: order_id (deterministic, stabil untuk retry).
    """
    conn = _get_conn(db_path)
    _init_db(conn)

    oid   = _order_id(order)
    dhash = _draft_hash(order)
    now_s = datetime.now(tz=TZ_JKT).isoformat()

    existing = conn.execute(
        "SELECT revision, draft_hash, confirmed FROM orders WHERE order_id=?", (oid,)
    ).fetchone()

    if existing:
        if existing["confirmed"] and existing["draft_hash"] == dhash:
            # Sudah confirmed + hash sama → tidak boleh overwrite
            conn.close()
            return oid
        revision = existing["revision"] + 1
        conn.execute("""
            UPDATE orders SET revision=?, draft_hash=?, status=?, order_json=?, updated_at=?
            WHERE order_id=?
        """, (revision, dhash, order.status.value, order.to_json(), now_s, oid))
    else:
        conn.execute("""
            INSERT INTO orders
                (order_id, revision, draft_hash, status, order_json, teks_asli,
                 confirmed, created_at, updated_at)
            VALUES (?,?,?,?,?,?,0,?,?)
        """, (oid, 0, dhash, order.status.value, order.to_json(), order.teks_asli, now_s, now_s))

    conn.commit()
    conn.close()
    return oid


def confirm_draft(order_id: str, db_path: Path = _DEFAULT_DB) -> bool:
    """Tandai order sebagai confirmed oleh user. Return True jika berhasil."""
    conn = _get_conn(db_path)
    _init_db(conn)
    now_s = datetime.now(tz=TZ_JKT).isoformat()
    cur = conn.execute(
        "UPDATE orders SET confirmed=1, updated_at=? WHERE order_id=?",
        (now_s, order_id)
    )
    conn.commit()
    ok = cur.rowcount > 0
    conn.close()
    return ok


def get_order(order_id: str, db_path: Path = _DEFAULT_DB) -> Optional[Order]:
    """Load order dari journal by ID."""
    conn = _get_conn(db_path)
    _init_db(conn)
    row = conn.execute(
        "SELECT order_json FROM orders WHERE order_id=?", (order_id,)
    ).fetchone()
    conn.close()
    if not row:
        return None
    return Order.from_dict(json.loads(row["order_json"]))


def get_commit_state(order_id: str, db_path: Path = _DEFAULT_DB) -> Optional[dict]:
    """
    Ambil state commit dari journal.
    Mengembalikan kolom live DAN dry terpisah.
    Return None jika tidak ditemukan.
    """
    conn = _get_conn(db_path)
    _init_db(conn)
    row = conn.execute("""
        SELECT order_id, revision, draft_hash, status, confirmed,
               doc_id, doc_url, doc_content_ok,
               event_id, event_url,
               dry_doc_id, dry_doc_url, dry_event_id, dry_event_url,
               commit_error
        FROM orders WHERE order_id=?
    """, (order_id,)).fetchone()
    conn.close()
    if not row:
        return None
    return dict(row)


def update_commit_state(
    order_id: str,
    *,
    # Live-mode resource IDs (hanya saat UMKM_GOOGLE_LIVE=1)
    doc_id:          Optional[str]  = None,
    doc_url:         Optional[str]  = None,
    doc_content_ok:  Optional[bool] = None,
    event_id:        Optional[str]  = None,
    event_url:       Optional[str]  = None,
    # Dry-run resource IDs (hanya saat dry-run)
    dry_doc_id:      Optional[str]  = None,
    dry_doc_url:     Optional[str]  = None,
    dry_event_id:    Optional[str]  = None,
    dry_event_url:   Optional[str]  = None,
    # Status & error
    status:          Optional[str]  = None,
    commit_error:    Optional[str]  = None,
    order_json:      Optional[str]  = None,
    # Mode flag — menentukan kolom mana yang diupdate
    dry_run:         bool           = False,
    db_path:         Path           = _DEFAULT_DB,
) -> None:
    """
    Update kolom commit di journal — atomic, per-resource.
    Dry-run IDs → kolom dry_*; Live IDs → kolom doc_id/event_id.
    Dipanggil segera setelah setiap resource berhasil dibuat.
    """
    conn = _get_conn(db_path)
    _init_db(conn)
    now_s = datetime.now(tz=TZ_JKT).isoformat()

    sets = ["updated_at=?"]
    vals = [now_s]

    if dry_run:
        # Dry-run: isi kolom dry_* saja, TIDAK isi kolom live
        for col, val in [
            ("dry_doc_id",    dry_doc_id    or doc_id),
            ("dry_doc_url",   dry_doc_url   or doc_url),
            ("dry_event_id",  dry_event_id  or event_id),
            ("dry_event_url", dry_event_url or event_url),
        ]:
            if val is not None:
                sets.append(f"{col}=?")
                vals.append(val)
    else:
        # Live mode: isi kolom live saja, TIDAK isi kolom dry_*
        for col, val in [
            ("doc_id",   doc_id),
            ("doc_url",  doc_url),
            ("event_id",  event_id),
            ("event_url", event_url),
        ]:
            if val is not None:
                sets.append(f"{col}=?")
                vals.append(val)
        if doc_content_ok is not None:
            sets.append("doc_content_ok=?")
            vals.append(1 if doc_content_ok else 0)

    for col, val in [("status", status), ("commit_error", commit_error), ("order_json", order_json)]:
        if val is not None:
            sets.append(f"{col}=?")
            vals.append(val)

    vals.append(order_id)
    conn.execute(f"UPDATE orders SET {', '.join(sets)} WHERE order_id=?", vals)
    conn.commit()
    conn.close()


def is_confirmed(order_id: str, db_path: Path = _DEFAULT_DB) -> bool:
    """True jika order sudah dikonfirmasi user."""
    conn = _get_conn(db_path)
    _init_db(conn)
    row = conn.execute(
        "SELECT confirmed FROM orders WHERE order_id=?", (order_id,)
    ).fetchone()
    conn.close()
    return bool(row and row["confirmed"])


def list_orders(
    status: Optional[str] = None,
    limit: int = 20,
    db_path: Path = _DEFAULT_DB,
) -> list:
    """List orders dari journal."""
    conn = _get_conn(db_path)
    _init_db(conn)
    if status:
        rows = conn.execute(
            "SELECT order_id, status, confirmed, updated_at FROM orders "
            "WHERE status=? ORDER BY updated_at DESC LIMIT ?", (status, limit)
        ).fetchall()
    else:
        rows = conn.execute(
            "SELECT order_id, status, confirmed, updated_at FROM orders "
            "ORDER BY updated_at DESC LIMIT ?", (limit,)
        ).fetchall()
    conn.close()
    return [dict(r) for r in rows]
