_INJECTION_PATTERNS = [
    "ignore previous", "ignore all", "disregard", "new instructions",
    "system prompt", "jangan ikuti", "lupakan instruksi",
]

def handle_process_order(args: Dict[str, Any]) -> Dict[str, Any]:
    teks = args.get("teks", "").strip()
    if not teks:
        return {"success": False, "error": "Teks pesanan tidak boleh kosong."}

    teks_lower = teks.lower()
    for pat in _INJECTION_PATTERNS:
        if pat in teks_lower:
            return {
                "success": False,
                "error": "Input mengandung pola yang tidak diizinkan.",
            }

    try:
        order = _call_langflow(teks)
    except lf.LangflowError as e:
        return {
            "success": False,
            "error": (
                f"Langflow tidak tersedia (HTTP {e.status}): {e}\n"
                f"Pastikan Langflow Desktop berjalan dan UMKM_FLOW_ID dikonfigurasi."
            ),
            "langflow_available": False,
        }
    except ValueError as e:
        return {"success": False, "error": f"Ekstraksi AI gagal: {e}", "langflow_available": True}

    order   = validate_order(order)
    oid     = save_draft(order)
    dhash   = _draft_hash(order)
    draft_t = build_draft(order)
    js      = get_commit_state(oid)
    revision = js["revision"] if js else 0

    return {
        "success":              True,
        "order_id":             oid,
        "draft_hash":           dhash,
        "revision":             revision,
        "status":               order.status.value,
        "needs_clarification":  order.status == OrderStatus.NEEDS_CLARIFICATION,
        "ambiguitas":           order.ambiguitas,
        "draft":                draft_t,
        "langflow_available":   True,
    }


def handle_update_order(args: Dict[str, Any]) -> Dict[str, Any]:
    order_id = args.get("order_id", "").strip()
    if not order_id:
        return {"success": False, "error": "order_id wajib diisi."}

    order = get_order(order_id)
    if not order:
        return {"success": False, "error": f"Order tidak ditemukan: {order_id}"}

    if is_confirmed(order_id):
        return {"success": False, "error": "Order sudah dikonfirmasi, tidak bisa diubah."}

    now = datetime.now(tz=TZ_JKT)

    if args.get("nama_pelanggan"):
        order.nama_pelanggan = args["nama_pelanggan"].strip()

    if args.get("jatuh_tempo_raw"):
        raw = args["jatuh_tempo_raw"].strip()
        order.jatuh_tempo_raw = raw
        from umkm_agent.parser import _extract_jatuh_tempo
        _, dt = _extract_jatuh_tempo(raw, now)
        order.jatuh_tempo_dt = dt

    if args.get("catatan"):
        order.catatan = args["catatan"].strip()

    if args.get("items_json"):
        try:
            raw_items = json.loads(args["items_json"])
            new_items = []
            for i in raw_items:
                if not isinstance(i, dict):
                    continue
                # S6-6: bool WAJIB ditolak SEBELUM float cast
                raw_q = i.get("jumlah", 0)
                if isinstance(raw_q, bool):
                    return {"success": False,
                            "error": f"Jumlah item '{i.get('nama','')}' tidak boleh boolean. Gunakan angka positif."}
                try:
                    q = float(raw_q)
                except (TypeError, ValueError):
                    return {"success": False,
                            "error": f"Jumlah item '{i.get('nama','')}' tidak bisa di-parse sebagai angka: {raw_q!r}"}
                if not math.isfinite(q):
                    return {"success": False,
                            "error": f"Jumlah item '{i.get('nama','')}' tidak valid ({raw_q}). Harus angka positif berhingga."}
                new_items.append(OrderItem(
                    nama=str(i.get("nama", "")),
                    jumlah=q,
                    satuan=str(i.get("satuan", "")),
                    catatan_item=i.get("catatan_item") or None,
                ))
            order.items = new_items
        except (json.JSONDecodeError, TypeError) as e:
            return {"success": False, "error": f"items_json tidak valid JSON: {e}"}

    order.diperbarui_pada = now

    # Resolve ambiguitas yang sudah terjawab SEBELUM revalidasi
    order = _resolve_ambiguitas(order)

    # Revalidasi — tambah isu baru jika masih ada field kosong
    order = validate_order(order)

    save_draft(order)
    dhash    = _draft_hash(order)
    draft_t  = build_draft(order)
    js_up    = get_commit_state(order_id)
    revision = js_up["revision"] if js_up else 0

    return {
        "success":              True,
        "order_id":             order_id,
        "draft_hash":           dhash,
        "revision":             revision,
        "status":               order.status.value,
        "needs_clarification":  order.status == OrderStatus.NEEDS_CLARIFICATION,
        "ambiguitas":           order.ambiguitas,
        "draft":                draft_t,
    }


def handle_confirm_commit(args: Dict[str, Any]) -> Dict[str, Any]:
    order_id = args.get("order_id", "").strip()
    if not order_id:
        return {"success": False, "error": "order_id wajib diisi."}

    # ── GUARD 1: confirmed WAJIB boolean True ────────────────────────────────
    confirmed_arg = args.get("confirmed")
    if confirmed_arg is not True:
        return {
            "success": False,
            "error": (
                "Konfirmasi eksplisit diperlukan. "
                "Sertakan confirmed=true (boolean) HANYA setelah user mengetik YA/KONFIRMASI. "
                "Jangan panggil tool ini tanpa konfirmasi user."
            ),
        }

    # ── GUARD 2: draft_hash WAJIB diisi ──────────────────────────────────────
    arg_hash = args.get("draft_hash", "").strip()
    if not arg_hash:
        return {
            "success": False,
            "error": (
                "draft_hash wajib diisi. "
                "Gunakan nilai draft_hash dari process_order atau update_order terakhir."
            ),
        }

    order = get_order(order_id)
    if not order:
        return {"success": False, "error": f"Order tidak ditemukan di journal: {order_id}"}

    js = get_commit_state(order_id)

    # ── GUARD 3: draft_hash harus cocok (stale-hash protection) ─────────────
    journal_hash = js["draft_hash"] if js else None
    if journal_hash and arg_hash != journal_hash:
        return {
            "success": False,
            "error": (
                "Draft sudah berubah sejak konfirmasi dikirim. "
                "Ambil draft terbaru dan konfirmasi ulang."
            ),
            "journal_hash": journal_hash,
            "provided_hash": arg_hash,
        }

    # ── Idempoten: sudah committed (per-mode check) ───────────────────────────
    # Dry-run lama (simulated) TIDAK boleh memblokir live commit.
    # committed = status=="committed" DAN resource live tersedia (live mode)
    #             ATAU status=="simulated" DAN dry-run mode
    live_mode = is_live_mode()
    if js:
        jstatus = js.get("status", "")
        if live_mode and jstatus == "committed" and js.get("doc_id"):
            # Live commit sudah selesai
            return {
                "success":          True,
                "status":           "already_committed",
                "message":          "Pesanan sudah tersimpan di Google (live) sebelumnya.",
                "google_doc_url":   js.get("doc_url") or order.google_doc_url,
                "google_event_url": js.get("event_url") or order.google_event_url,
                "dry_run":          False,
                "order_id":         order_id,
                "revision":         js.get("revision", 0),
            }
        if not live_mode and jstatus == "simulated" and js.get("dry_doc_id"):
            # Dry-run sudah selesai sebelumnya
            return {
                "success":          True,
                "status":           "already_committed",
                "message":          "Pesanan sudah disimulasikan (dry-run) sebelumnya.",
                "google_doc_url":   js.get("dry_doc_url"),
                "google_event_url": js.get("dry_event_url"),
                "dry_run":          True,
                "order_id":         order_id,
                "revision":         js.get("revision", 0),
            }

    # ── Revalidasi ketat ─────────────────────────────────────────────────────
    try:
        _revalidate_for_commit(order)
    except CommitValidationError as e:
        return {"success": False, "error": "Validasi gagal sebelum commit:", "issues": e.issues}

    # ── Tandai confirmed di journal ───────────────────────────────────────────
    confirm_draft(order_id)
    dry = not live_mode

    # ── Persist callbacks — dipanggil di DALAM commit_docs setelah tiap sub-step ──
    # _on_doc_created: dipanggil tepat setelah create_doc sukses, SEBELUM insert.
    # _on_content_ok:  dipanggil tepat setelah insert/reconcile sukses.
    # Keduanya write ke journal DB sehingga crash saat insert tidak kehilangan doc_id.
    def _persist_doc_created(doc_id_val: str, doc_url_val: str) -> None:
        update_commit_state(
            order_id,
            doc_id  = doc_id_val,
            doc_url = doc_url_val,
            dry_run = dry,
        )

    def _persist_content_ok(doc_id_val: str, doc_url_val: str) -> None:
        update_commit_state(
            order_id,
            doc_id         = doc_id_val,
            doc_url        = doc_url_val,
            doc_content_ok = True,
            dry_run        = dry,
        )

    # ── Commit Docs (per-step, persist di dalam fungsi via callbacks) ─────────
    try:
        doc_result = _commit_docs(
            order, order_id,
            journal_state    = js or {},
            _on_doc_created  = _persist_doc_created,
            _on_content_ok   = _persist_content_ok,
        )
    except Exception as e:
        return {"success": False, "error": f"Commit Docs gagal: {e}", "order_id": order_id}

    # Persist final doc state (terutama content_ok jika callback belum jalan)
    update_commit_state(
        order_id,
        doc_id         = doc_result.get("doc_id"),
        doc_url        = doc_result.get("doc_url"),
        doc_content_ok = doc_result.get("doc_content_ok"),
        dry_run        = dry,
    )

    # ── Commit Calendar HANYA jika Docs tidak punya error ────────────────────
    # Jika Docs gagal (termasuk persist callback error), Calendar TIDAK dijalankan.
    # User harus retry dari awal — Calendar bisa terjadi di retry berikutnya
    # setelah Docs berhasil.
    doc_errors = doc_result.get("errors", {})
    if doc_errors:
        cal_result: Dict[str, Any] = {
            "event_id":  None,
            "event_url": None,
            "errors":    {"calendar": "Ditunda karena Docs belum berhasil — retry confirm_commit."},
            "dry_run":   dry,
        }
    else:
        try:
            cal_result = _commit_calendar(order, order_id, journal_state=js or {})
        except Exception as e:
            cal_result = {"event_id": None, "event_url": None, "errors": {"calendar": str(e)}, "dry_run": dry}

    update_commit_state(
        order_id,
        event_id  = cal_result.get("event_id"),
        event_url = cal_result.get("event_url"),
        dry_run   = dry,
    )

    # ── Tentukan status final ─────────────────────────────────────────────────
    all_errors = {**doc_result.get("errors", {}), **cal_result.get("errors", {})}
    if all_errors:
        final_status = OrderStatus.FAILED
    elif dry:
        final_status = OrderStatus.SIMULATED
    else:
        final_status = OrderStatus.COMMITTED
        order.google_doc_id    = doc_result.get("doc_id")
        order.google_doc_url   = doc_result.get("doc_url")
        order.google_event_id  = cal_result.get("event_id")
        order.google_event_url = cal_result.get("event_url")

    order.status = final_status

    # Dry-run: TIDAK menyimpan google IDs di order_json (tetap None)
    if dry:
        order.google_doc_id    = None
        order.google_doc_url   = None
        order.google_event_id  = None
        order.google_event_url = None

    update_commit_state(
        order_id,
        status       = final_status.value,
        commit_error = json.dumps(all_errors) if all_errors else None,
        order_json   = order.to_json(),
        dry_run      = dry,
    )

    if all_errors:
        return {
            "success":   False,
            "status":    final_status.value,
            "errors":    all_errors,
            "partial":   {
                "doc_url":   doc_result.get("doc_url"),
                "event_url": cal_result.get("event_url"),
            },
            "order_id": order_id,
            "message":  "Commit sebagian gagal. Panggil confirm_commit lagi (confirmed=true, draft_hash=<hash>) untuk retry.",
            "dry_run":  dry,
        }

    js_final = get_commit_state(order_id)
    revision = js_final["revision"] if js_final else 0
    summary  = build_draft(order)
    return {
        "success":          True,
        "status":           final_status.value,
        "order_id":         order_id,
        "revision":         revision,
        "google_doc_url":   doc_result.get("doc_url"),
        "google_event_url": cal_result.get("event_url"),
        "dry_run":          dry,
        "summary":          summary,
        "message": (
            "✅ Pesanan disimulasikan (DRY-RUN — tidak ada perubahan nyata ke Google)."
            if dry else
            "✅ Pesanan tersimpan ke Google Docs & Calendar."
        ),
    }


