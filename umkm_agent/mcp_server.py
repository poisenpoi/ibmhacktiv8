# ── MCP JSON-RPC 2.0 ─────────────────────────────────────────────────────────

_HANDLERS = {
    "process_order":  handle_process_order,
    "update_order":   handle_update_order,
    "confirm_commit": handle_confirm_commit,
    "check_status":   handle_check_status,
}

def _send(obj: Dict[str, Any]) -> None:
    sys.stdout.write(json.dumps(obj, ensure_ascii=False) + "\n")
    sys.stdout.flush()

def _handle(msg: Dict[str, Any]) -> None:
    mid    = msg.get("id")
    method = msg.get("method", "")
    if method == "initialize":
        _send({"jsonrpc": "2.0", "id": mid, "result": {
            "protocolVersion": "2024-11-05",
            "capabilities": {"tools": {}},
            "serverInfo": {"name": "umkm-order-assistant", "version": "1.0.0"},
        }})
        return
    if method == "notifications/initialized":
        return
    if method == "tools/list":
        _send({"jsonrpc": "2.0", "id": mid, "result": {
            "tools": [{"name": n, **d} for n, d in TOOLS.items()]
        }})
        return
    if method == "tools/call":
        params    = msg.get("params", {})
        tool_name = params.get("name", "")
        tool_args = params.get("arguments", {})
        handler   = _HANDLERS.get(tool_name)
        if not handler:
            _send({"jsonrpc": "2.0", "id": mid,
                   "error": {"code": -32601, "message": f"Tool tidak dikenal: {tool_name}"}})
            return
        try:
            res = handler(tool_args)
            # Eject "draft" dari JSON agar ditampilkan sebagai plain text (bukan
            # escaped \n di dalam string JSON). Bob membaca semua content items.
            draft_text: Optional[str] = res.pop("draft", None) if isinstance(res, dict) else None
            content_items = [{"type": "text", "text": json.dumps(res, ensure_ascii=False, indent=2)}]
            if draft_text:
                content_items.append({"type": "text", "text": "\n" + draft_text})
            _send({"jsonrpc": "2.0", "id": mid, "result": {"content": content_items}})
        except Exception as e:
            _send({"jsonrpc": "2.0", "id": mid,
                   "error": {"code": -32603, "message": str(e), "data": traceback.format_exc()}})
        return
    if mid is not None:
        _send({"jsonrpc": "2.0", "id": mid,
               "error": {"code": -32601, "message": f"Method tidak dikenal: {method}"}})

def main() -> None:
    for raw in sys.stdin:
        raw = raw.strip()
        if not raw:
            continue
        try:
            msg = json.loads(raw)
        except json.JSONDecodeError:
            _send({"jsonrpc": "2.0", "id": None,
                   "error": {"code": -32700, "message": "Parse error"}})
            continue
        _handle(msg)

if __name__ == "__main__":
    main()
