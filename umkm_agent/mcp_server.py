# ── Langflow → Order parser ───────────────────────────────────────────────────

def _parse_llm_json(llm_text: str, teks_asli: str) -> Order:
    """
    Parse output LLM menjadi Order. Raise ValueError jika gagal. NO silent fallback.

    Prioritas jatuh_tempo_dt:
      1. Field "jatuh_tempo_dt" di JSON LLM → ISO 8601 timezone-aware.
         LLM diperintahkan mengisi ini hanya jika tanggal+jam keduanya jelas.
      2. Fallback ke _extract_jatuh_tempo(jatuh_tempo_raw) — offline regex.
      Jika keduanya gagal → jatuh_tempo_dt = None (perlu klarifikasi).
    """
    text = llm_text.strip()
    # Strip markdown code fence jika ada
    if text.startswith("```"):
        lines = text.split("\n")
        inner = lines[1:] if len(lines) > 1 else lines
        if inner and inner[-1].strip() == "```":
            inner = inner[:-1]
        text = "\n".join(inner).strip()

    try:
        d = json.loads(text)
    except json.JSONDecodeError as e:
        raise ValueError(
            f"LLM tidak mengembalikan JSON valid.\nError: {e}\n"
            f"Output LLM (200 char): {llm_text[:200]}"
        )

    now = datetime.now(tz=TZ_JKT)
    items = []
    item_ambiguitas: list = []
    for raw in d.get("items", []):
        if not isinstance(raw, dict):
            continue
        nama = str(raw.get("nama", "")).strip()
        if not nama:
            continue
        # S6-6: bool WAJIB ditolak SEBELUM float cast (bool adalah subclass float)
        raw_q = raw.get("jumlah", 0)
        if isinstance(raw_q, bool):
            item_ambiguitas.append(
                f"Jumlah '{nama}' adalah boolean — harus angka positif."
            )
            jumlah = 0.0
        else:
            try:
                jumlah = float(raw_q)
            except (TypeError, ValueError):
                jumlah = 0.0
            if not math.isfinite(jumlah):
                item_ambiguitas.append(
                    f"Jumlah '{nama}' tidak valid ({raw_q}) — harus angka positif berhingga."
                )
                jumlah = 0.0
        satuan = str(raw.get("satuan", "")).strip()
        items.append(OrderItem(nama=nama, jumlah=jumlah, satuan=satuan,
                               catatan_item=raw.get("catatan_item") or None))

    jatuh_tempo_raw = d.get("jatuh_tempo_raw") or None
    jatuh_tempo_dt  = None

    # ── Prioritas 1: LLM mengembalikan ISO datetime langsung ────────────────
    llm_dt_str = d.get("jatuh_tempo_dt") or None
    if llm_dt_str and str(llm_dt_str).strip() not in ("null", "None", ""):
        try:
            parsed = datetime.fromisoformat(str(llm_dt_str).strip())
            # Wajib timezone-aware — jika naive, asumsikan Asia/Jakarta
            if parsed.tzinfo is None or parsed.tzinfo.utcoffset(parsed) is None:
                parsed = parsed.replace(tzinfo=TZ_JKT)
            jatuh_tempo_dt = parsed
        except (ValueError, TypeError):
            # LLM mengembalikan format tidak valid — lanjut ke fallback
            jatuh_tempo_dt = None

    # ── Prioritas 2: Fallback ke offline regex pada jatuh_tempo_raw ─────────
    if jatuh_tempo_dt is None and jatuh_tempo_raw:
        from umkm_agent.parser import _extract_jatuh_tempo
        _, jatuh_tempo_dt = _extract_jatuh_tempo(jatuh_tempo_raw, now)

    # Gabungkan ambiguitas dari LLM dan dari item qty invalid
    ambiguitas = list(d.get("ambiguitas", [])) + item_ambiguitas
    order = Order(
        nama_pelanggan  = d.get("nama_pelanggan") or None,
        items           = items,
        jatuh_tempo_raw = jatuh_tempo_raw,
        jatuh_tempo_dt  = jatuh_tempo_dt,
        catatan         = d.get("catatan") or None,
        ambiguitas      = ambiguitas,
        teks_asli       = teks_asli,
        dibuat_pada     = now,
        diperbarui_pada = now,
        status = OrderStatus.NEEDS_CLARIFICATION if ambiguitas else OrderStatus.DRAFT,
    )
    return order


def _call_langflow(teks: str) -> Order:
    """Kirim teks ke Langflow. FAIL JELAS jika tidak berhasil."""
    flow_id = lf.UMKM_FLOW_ID
    if not flow_id:
        raise lf.LangflowError(
            "UMKM_FLOW_ID tidak dikonfigurasi. Import flow di Langflow, lalu isi ID di .bob/mcp.json."
        )
    now_iso = datetime.now(tz=TZ_JKT).isoformat()
    teks_ctx = f"[Waktu sekarang Asia/Jakarta: {now_iso}]\n\n{teks}"
    resp = lf.run_flow(teks_ctx, flow_id=flow_id)
    return _parse_llm_json(resp["output_text"], teks)


# ── Commit-time validation ────────────────────────────────────────────────────

class CommitValidationError(Exception):
    def __init__(self, issues: list):
        self.issues = issues
        super().__init__("\n".join(issues))


def _revalidate_for_commit(order: Order) -> None:
    """
    Validasi ketat sebelum commit.
    - qty: math.isfinite() + tolak boolean (True/False bukan angka valid)
    - jatuh_tempo_dt: wajib timezone-aware; naive datetime → error terkontrol
    - jatuh_tempo_dt: harus di masa depan
    - ambiguitas: harus kosong
    Raise CommitValidationError jika ada masalah.
    """
    issues = []
    now = datetime.now(tz=TZ_JKT)

    if not order.nama_pelanggan or not order.nama_pelanggan.strip():
        issues.append("Nama pelanggan kosong.")

    if not order.items:
        issues.append("Tidak ada item pesanan.")
    else:
        for item in order.items:
            q = item.jumlah
            # boolean adalah subclass float di Python — tolak eksplisit
            if isinstance(q, bool):
                issues.append(f"Jumlah '{item.nama}' adalah boolean, bukan angka.")
            elif not math.isfinite(q) or q <= 0:
                issues.append(
                    f"Jumlah '{item.nama}' tidak valid ({q}). "
                    f"Harus angka positif berhingga."
                )
            if not item.satuan or not item.satuan.strip():
                issues.append(f"Satuan '{item.nama}' kosong.")

    dt = order.jatuh_tempo_dt
    if dt is None:
        issues.append("Jatuh tempo tidak ada atau tidak dapat diparsing.")
    else:
        # Cek naive datetime secara eksplisit — bukan TypeError
        if dt.tzinfo is None or dt.tzinfo.utcoffset(dt) is None:
            issues.append(
                "Jatuh tempo tidak timezone-aware. "
                "Gunakan format lengkap misal '25/01/2025 jam 14:00'."
            )
        else:
            try:
                if dt <= now:
                    issues.append(
                        f"Jatuh tempo sudah lewat: "
                        f"{dt.strftime('%d/%m/%Y %H:%M WIB')}. "
                        f"Gunakan tanggal di masa depan."
                    )
            except TypeError:
                # Seharusnya tidak terjadi setelah cek di atas, tapi guard tetap ada
                issues.append("Jatuh tempo tidak dapat dibandingkan dengan waktu sekarang.")

    if order.ambiguitas:
        issues.append(
            f"Masih ada {len(order.ambiguitas)} pertanyaan yang belum dijawab: "
            + "; ".join(order.ambiguitas[:2])
            + ("..." if len(order.ambiguitas) > 2 else "")
        )

    if issues:
        raise CommitValidationError(issues)


# ── Ambiguitas resolver ───────────────────────────────────────────────────────

def _resolve_ambiguitas(order: Order) -> Order:
    """
    Hapus pertanyaan klarifikasi yang sudah terjawab dari order.ambiguitas.
    Strategi: cek apakah field yang ditanyakan sudah terisi.
    Jika semua field terisi → ambiguitas terkait dihapus.
    Pertanyaan yang tidak dikenali tetap dipertahankan.
    """
    if not order.ambiguitas:
        return order

    resolved = []
    remaining = []

    for q in order.ambiguitas:
        q_lower = q.lower()
        answered = False

        # Cek nama pelanggan
        if ("nama" in q_lower or "pelanggan" in q_lower) and order.nama_pelanggan:
            answered = True

        # Cek jatuh tempo — tanggal + jam
        elif ("jatuh tempo" in q_lower or "kapan" in q_lower or "tanggal" in q_lower):
            if order.jatuh_tempo_dt is not None:
                answered = True  # tanggal + jam sudah ada

        # Cek jam spesifik
        elif "jam" in q_lower and "berapa" in q_lower:
            if order.jatuh_tempo_dt is not None and order.jatuh_tempo_raw and (
                "jam" in (order.jatuh_tempo_raw or "").lower()
                or ":" in (order.jatuh_tempo_raw or "")
                or "pukul" in (order.jatuh_tempo_raw or "").lower()
            ):
                answered = True

        # Cek items
        elif ("item" in q_lower or "pesanan" in q_lower or "barang" in q_lower) and order.items:
            answered = True

        # Cek satuan spesifik per item
        elif "satuan" in q_lower or ("kg" in q_lower and "gram" in q_lower):
            # Cek apakah semua item sudah punya satuan valid
            if order.items and all(i.satuan and i.satuan.strip() for i in order.items):
                answered = True

        if answered:
            resolved.append(q)
        else:
            remaining.append(q)

    order.ambiguitas = remaining
    return order


