"""
draft_builder.py - Membangun teks draft ringkasan pesanan untuk konfirmasi user
Asisten Pesanan UMKM | Generated by IBM Bob

Hanya dipanggil jika order.status == DRAFT (tidak ada ambiguitas).
Output adalah teks human-readable yang dikirim ke user sebelum commit.
"""
from __future__ import annotations

from .models import Order, OrderStatus


_SEPARATOR = "─" * 48


def build_draft(order: Order) -> str:
    """
    Buat teks draft untuk ditampilkan ke user sebelum konfirmasi.
    Jika order masih NEEDS_CLARIFICATION, kembalikan pertanyaan klarifikasi saja.
    """
    if order.status == OrderStatus.NEEDS_CLARIFICATION:
        return _build_clarification(order)

    if order.status == OrderStatus.COMMITTED:
        return _build_committed_summary(order)

    return _build_draft_text(order)


def _build_clarification(order: Order) -> str:
    lines = [
        "⚠️  **Data pesanan belum lengkap / ambigu.**",
        "",
        "Saya membutuhkan klarifikasi berikut sebelum dapat membuat draft:",
        "",
    ]
    for i, q in enumerate(order.ambiguitas, 1):
        lines.append(f"{i}. {q}")
    lines += [
        "",
        "Mohon jawab pertanyaan di atas, lalu kirim ulang atau lengkapi pesanannya.",
    ]
    return "\n".join(lines)


def _build_draft_text(order: Order) -> str:
    from zoneinfo import ZoneInfo
    TZ_JKT = ZoneInfo("Asia/Jakarta")

    jatuh_tempo_str = "—"
    if order.jatuh_tempo_dt:
        dt = order.jatuh_tempo_dt
        hari_map = {0: "Senin", 1: "Selasa", 2: "Rabu", 3: "Kamis",
                    4: "Jumat", 5: "Sabtu", 6: "Minggu"}
        hari = hari_map.get(dt.weekday(), "")
        jatuh_tempo_str = dt.strftime(f"{hari}, %d/%m/%Y pukul %H:%M WIB")

    item_lines = [item.display() for item in order.items]

    catatan_str = order.catatan if order.catatan else "—"

    lines = [
        _SEPARATOR,
        "📋 **DRAFT PESANAN — Mohon konfirmasi**",
        _SEPARATOR,
        f"👤 Pelanggan  : {order.nama_pelanggan}",
        f"📅 Jatuh Tempo: {jatuh_tempo_str}",
        f"📝 Catatan    : {catatan_str}",
        "",
        "🛒 Daftar Pesanan:",
    ]
    lines.extend(item_lines)
    lines += [
        "",
        _SEPARATOR,
        "Ketik **YA** atau **KONFIRMASI** untuk menyimpan ke Google Docs & Calendar.",
        "Ketik **BATAL** untuk membatalkan.",
        "Atau koreksi data di atas dan kirim ulang.",
        _SEPARATOR,
    ]
    return "\n".join(lines)


def _build_committed_summary(order: Order) -> str:
    jatuh_tempo_str = "—"
    if order.jatuh_tempo_dt:
        dt = order.jatuh_tempo_dt
        hari_map = {0: "Senin", 1: "Selasa", 2: "Rabu", 3: "Kamis",
                    4: "Jumat", 5: "Sabtu", 6: "Minggu"}
        hari = hari_map.get(dt.weekday(), "")
        jatuh_tempo_str = dt.strftime(f"{hari}, %d/%m/%Y pukul %H:%M WIB")

    lines = [
        _SEPARATOR,
        "✅ **PESANAN TERSIMPAN**",
        _SEPARATOR,
        f"👤 Pelanggan  : {order.nama_pelanggan}",
        f"📅 Jatuh Tempo: {jatuh_tempo_str}",
    ]
    if order.google_doc_url:
        lines.append(f"📄 Google Docs : {order.google_doc_url}")
    if order.google_event_url:
        lines.append(f"📅 Calendar    : {order.google_event_url}")
    lines.append(_SEPARATOR)
    return "\n".join(lines)


def build_clarification_prompt(order: Order) -> str:
    """
    Kembalikan hanya daftar pertanyaan klarifikasi (untuk tool response).
    """
    if not order.ambiguitas:
        return ""
    questions = "\n".join(f"- {q}" for q in order.ambiguitas)
    return f"Pertanyaan klarifikasi:\n{questions}"
