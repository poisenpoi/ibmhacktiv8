def save_to_google_docs(
    order: Order,
    order_id: str,
    *,
    existing_doc_id: Optional[str] = None,
    doc_content_ok: bool = False,
    _services: Optional[_GoogleServices] = None,
) -> Tuple[str, str, bool]:
    """
    Simpan pesanan ke Google Docs.

    Idempoten per-step:
      - existing_doc_id != None → skip create, hanya insert content jika belum ok
      - doc_content_ok = True → kedua step sudah selesai, return langsung

    Args:
        order: Order yang akan disimpan
        order_id: ID dari journal (untuk idempoten lookup)
        existing_doc_id: doc_id dari journal (jika sudah pernah dibuat)
        doc_content_ok: True jika content sudah berhasil diinsert sebelumnya
        _services: injectable untuk testing

    Returns:
        (doc_id, doc_url, content_ok)

    Raises:
        RuntimeError: jika live mode tapi credential tidak siap
        ImportError: jika library tidak terinstall
    """
    if not _LIVE:
        # DRY-RUN — placeholder eksplisit, bukan URL nyata
        doc_id  = existing_doc_id or _dry_doc_id(order_id)
        doc_url = _dry_doc_url(order_id)
        return doc_id, doc_url, True

    # LIVE MODE
    token_path = os.environ.get("UMKM_GOOGLE_TOKEN", ".secrets/token.json")
    svc = _services or _GoogleServices(token_path, REQUIRED_SCOPES)

    # Step 1: Create doc (idempoten — skip jika sudah ada)
    # PENTING: doc_id harus di-return bahkan jika step 2 gagal,
    # agar retry tidak membuat doc baru.
    doc_id = existing_doc_id
    if not doc_id:
        doc_id = svc.create_doc(_doc_title(order))
    # doc_id SUDAH VALID di sini — simpan sebelum step 2

    doc_url = f"https://docs.google.com/document/d/{doc_id}/edit"

    # Step 2: Insert content (idempoten — skip jika sudah ok / marker sudah ada)
    if not doc_content_ok:
        if svc.doc_has_content(doc_id, order_id):
            doc_content_ok = True  # sudah ada, skip insert
        else:
            svc.insert_doc_content(doc_id, _doc_content(order, order_id))
            doc_content_ok = True

    return doc_id, doc_url, doc_content_ok


def save_to_google_calendar(
    order: Order,
    order_id: str,
    *,
    existing_event_id: Optional[str] = None,
    _services: Optional[_GoogleServices] = None,
) -> Tuple[str, str]:
    """
    Buat event reminder di Google Calendar.

    Idempoten:
      - existing_event_id != None → return langsung
      - Cari event existing by order_id di description sebelum create

    Args:
        order: Order yang akan disimpan
        order_id: ID dari journal
        existing_event_id: event_id dari journal (jika sudah pernah dibuat)
        _services: injectable untuk testing

    Returns:
        (event_id, event_url)

    TIDAK mengirim undangan ke pelanggan (attendees kosong).
    """
    if not _LIVE:
        evt_id  = existing_event_id or _dry_evt_id(order_id)
        evt_url = _dry_evt_url(order_id)
        return evt_id, evt_url

    # LIVE MODE
    token_path = os.environ.get("UMKM_GOOGLE_TOKEN", ".secrets/token.json")
    svc = _services or _GoogleServices(token_path, REQUIRED_SCOPES)

    # Idempoten: gunakan existing jika ada
    if existing_event_id:
        try:
            evt_url = svc.get_event_html_link(existing_event_id)
        except Exception:
            evt_url = f"https://calendar.google.com/calendar/event?eid={existing_event_id}"
        return existing_event_id, evt_url

    # Lookup by order_id (cegah duplikasi jika response hilang)
    found_id = svc.find_event_by_order_id(order_id)
    if found_id:
        evt_url = svc.get_event_html_link(found_id)   # propagate error jika GET gagal
        return found_id, evt_url

    # Create new
    event_body = _calendar_event_body(order, order_id)
    evt_id, html_link = svc.create_event(event_body)
    evt_url = html_link or f"https://calendar.google.com/calendar/event?eid={evt_id}"
    return evt_id, evt_url


def commit_docs(
    order: Order,
    order_id: str,
    *,
    journal_state: Optional[dict] = None,
    _services: Optional[_GoogleServices] = None,
    _on_doc_created: Optional[Callable] = None,
    _on_content_ok: Optional[Callable] = None,
) -> Dict[str, Any]:
    """
    Commit hanya langkah Google Docs (bukan Calendar).
    Idempoten per-step via journal_state.
    Return dict: doc_id, doc_url, doc_content_ok, errors, dry_run.

    Untuk dry-run: kolom dry_doc_id/dry_doc_url dari journal_state.
    Untuk live: kolom doc_id/doc_url.

    Args (callbacks — injektabel untuk persist-before-insert):
        _on_doc_created(doc_id, doc_url):
            Dipanggil TEPAT SETELAH create_doc sukses, SEBELUM insert_doc_content.
            Gunakan ini untuk persist doc_id ke journal — sehingga crash saat insert
            tidak menyebabkan doc baru dibuat saat retry.
        _on_content_ok(doc_id, doc_url):
            Dipanggil tepat setelah insert_doc_content (atau reconcile) sukses.
    """
    js = journal_state or {}
    dry = not _LIVE

    # Pilih kolom yang tepat berdasarkan mode
    if dry:
        existing_doc = js.get("dry_doc_id")
        existing_url = js.get("dry_doc_url")
        content_already_ok = False  # dry-run tidak punya content state
    else:
        existing_doc = js.get("doc_id")
        existing_url = js.get("doc_url")
        content_already_ok = bool(js.get("doc_content_ok"))

    result: Dict[str, Any] = {
        "doc_id":         existing_doc,
        "doc_url":        existing_url,
        "doc_content_ok": content_already_ok,
        "errors":         {},
        "dry_run":        dry,
    }

    if result["doc_id"] and result["doc_content_ok"]:
        return result  # semua langkah sudah selesai

    if dry:
        doc_id  = existing_doc or _dry_doc_id(order_id)
        doc_url = _dry_doc_url(order_id)
        result["doc_id"]         = doc_id
        result["doc_url"]        = doc_url
        result["doc_content_ok"] = True  # dry-run tidak ada partial
        # Persist dry IDs segera — error WAJIB diteruskan (jangan swallow)
        if _on_doc_created:
            _on_doc_created(doc_id, doc_url)
        return result

    # LIVE MODE — dua langkah terpisah dengan persist callback di antara keduanya
    token_path = os.environ.get("UMKM_GOOGLE_TOKEN", ".secrets/token.json")
    svc = _services or _GoogleServices(token_path, REQUIRED_SCOPES)

    doc_id = existing_doc
    # Step 1: create doc jika belum ada
    if not doc_id:
        try:
            doc_id = svc.create_doc(_doc_title(order))
            doc_url = f"https://docs.google.com/document/d/{doc_id}/edit"
            result["doc_id"]  = doc_id
            result["doc_url"] = doc_url
            # ── PERSIST SEGERA setelah create_doc — SEBELUM insert_doc_content ──
            # Jika proses crash antara sini dan insert, retry bisa skip create_doc
            # karena doc_id sudah ada di journal.
            # Error WAJIB diteruskan — jika persist gagal, JANGAN lanjut ke Calendar
            if _on_doc_created:
                _on_doc_created(doc_id, doc_url)
        except Exception as e:
            result["errors"]["docs_create"] = str(e)
            return result  # tidak bisa lanjut tanpa doc_id

    if not result.get("doc_url"):
        result["doc_url"] = f"https://docs.google.com/document/d/{doc_id}/edit"

    # Step 2: reconcile + insert content jika belum ok
    if not result["doc_content_ok"]:
        try:
            # Cegah insert ganda: cek marker di dokumen (idempoten saat response hilang)
            if svc.doc_has_content(doc_id, order_id):
                result["doc_content_ok"] = True  # sudah ada, skip insert
            else:
                content = _doc_content(order, order_id)
                svc.insert_doc_content(doc_id, content)
                result["doc_content_ok"] = True
            # ── PERSIST content_ok segera setelah berhasil ──────────────────────
            # Error WAJIB diteruskan — jika persist gagal, caller harus tahu
            if _on_content_ok:
                _on_content_ok(doc_id, result["doc_url"])
        except Exception as e:
            result["errors"]["docs_content"] = str(e)
            # doc_id sudah tersimpan di journal (via _on_doc_created) — retry aman

    return result


def commit_calendar(
    order: Order,
    order_id: str,
    *,
    journal_state: Optional[dict] = None,
    _services: Optional[_GoogleServices] = None,
) -> Dict[str, Any]:
    """
    Commit hanya langkah Google Calendar.
    Idempoten via journal_state dan deterministic event ID.
    Return dict: event_id, event_url, errors, dry_run.
    """
    js = journal_state or {}
    dry = not _LIVE

    if dry:
        existing_evt = js.get("dry_event_id")
        existing_url = js.get("dry_event_url")
    else:
        existing_evt = js.get("event_id")
        existing_url = js.get("event_url")

    result: Dict[str, Any] = {
        "event_id":  existing_evt,
        "event_url": existing_url,
        "errors":    {},
        "dry_run":   dry,
    }

    if result["event_id"]:
        return result  # sudah ada

    if dry:
        evt_id  = _dry_evt_id(order_id)
        evt_url = _dry_evt_url(order_id)
        result["event_id"]  = evt_id
        result["event_url"] = evt_url
        return result

    # LIVE MODE
    token_path = os.environ.get("UMKM_GOOGLE_TOKEN", ".secrets/token.json")
    svc = _services or _GoogleServices(token_path, REQUIRED_SCOPES)

    try:
        evt_id, evt_url = save_to_google_calendar(
            order, order_id, _services=svc,
        )
        result["event_id"]  = evt_id
        result["event_url"] = evt_url
    except Exception as e:
        result["errors"]["calendar"] = str(e)

    return result


def commit_order(
    order: Order,
    order_id: str,
    *,
    journal_state: Optional[dict] = None,
    _services: Optional[_GoogleServices] = None,
) -> Tuple[Order, dict]:
    """
    Commit order ke Google Docs & Calendar (combined, untuk backward compat).
    Gunakan commit_docs() + commit_calendar() secara terpisah di MCP handler
    untuk mendapatkan per-step journal persist.

    Returns:
        (order, commit_result) di mana commit_result berisi:
          doc_id, doc_url, doc_content_ok, event_id, event_url,
          errors: {}, dry_run: bool
    """
    doc_result = commit_docs(order, order_id, journal_state=journal_state, _services=_services)
    cal_result = commit_calendar(order, order_id, journal_state=journal_state, _services=_services)

    errors = {**doc_result.get("errors", {}), **cal_result.get("errors", {})}
    dry = not _LIVE

    commit_result: Dict[str, Any] = {
        "doc_id":         doc_result.get("doc_id"),
        "doc_url":        doc_result.get("doc_url"),
        "doc_content_ok": doc_result.get("doc_content_ok", False),
        "event_id":       cal_result.get("event_id"),
        "event_url":      cal_result.get("event_url"),
        "errors":         errors,
        "dry_run":        dry,
    }

    if errors:
        order.status = OrderStatus.FAILED
    elif dry:
        order.status = OrderStatus.SIMULATED
        # Dry-run: TIDAK mengisi google_doc_id/event_id di order — tetap None
    else:
        order.status = OrderStatus.COMMITTED
        order.google_doc_id    = commit_result["doc_id"]
        order.google_doc_url   = commit_result["doc_url"]
        order.google_event_id  = commit_result["event_id"]
        order.google_event_url = commit_result["event_url"]

    order.diperbarui_pada = datetime.now(tz=TZ_JKT)
    return order, commit_result


