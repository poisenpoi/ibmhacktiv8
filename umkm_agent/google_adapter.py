# ── Marker untuk Docs content reconcile (cegah insert ganda) ────────────────
_UMKM_MARKER_PREFIX = "UMKM_ORDER_ID:"

def _deterministic_event_id(order_id: str) -> str:
    """
    Generate deterministic Google Calendar event ID dari order_id.
    Format yang valid: hanya [a-v0-9], panjang 5-40 karakter.
    SHA-256 lalu filter karakter valid → ambil 20 karakter pertama.
    """
    raw = hashlib.sha256(order_id.encode()).hexdigest()
    # hexdigest menggunakan [0-9a-f]; mapping: a-f → a-f, 0-9 → 0-9
    # semua karakter sudah masuk [a-v0-9] karena [a-f] ⊂ [a-v]
    filtered = re.sub(r'[^a-v0-9]', '', raw)
    return filtered[:20]

