def _doc_title(order: Order) -> str:
    date_str = order.jatuh_tempo_dt.strftime("%d%m%Y") if order.jatuh_tempo_dt else "nodate"
    safe_name = (order.nama_pelanggan or "Unknown").replace("/", "-")
    return f"Pesanan-UMKM-{safe_name}-{date_str}"


def _doc_content(order: Order, order_id: str) -> str:
    """
    Build teks dokumen pesanan.
    Baris pertama selalu berisi marker UMKM_ORDER_ID:<order_id>
    untuk reconcile (cegah insert ganda saat response hilang).
    """
    jt = "—"
    if order.jatuh_tempo_dt:
        dt = order.jatuh_tempo_dt
        hari = ["Senin","Selasa","Rabu","Kamis","Jumat","Sabtu","Minggu"][dt.weekday()]
        jt = dt.strftime(f"{hari}, %d/%m/%Y pukul %H:%M WIB")
    items_str = "\n".join(
        f"  {i+1}. {item.nama} — {item.jumlah} {item.satuan}"
        + (f" ({item.catatan_item})" if item.catatan_item else "")
        for i, item in enumerate(order.items)
    )
    return (
        f"{_UMKM_MARKER_PREFIX}{order_id}\n"
        f"PESANAN UMKM\n{'='*40}\n"
        f"Pelanggan   : {order.nama_pelanggan}\n"
        f"Jatuh Tempo : {jt}\n"
        f"Catatan     : {order.catatan or '—'}\n\n"
        f"DAFTAR PESANAN:\n{items_str}\n"
    )


def _calendar_event_body(order: Order, order_id: str) -> dict:
    """
    Build calendar event body. attendees = [] (no invite to customer).
    id = deterministic dari order_id agar create idempoten (HTTP 409 = already exists).
    """
    start_dt = order.jatuh_tempo_dt
    end_dt = start_dt + timedelta(hours=1)
    item_summary = ", ".join(
        f"{item.jumlah}{item.satuan} {item.nama}" for item in order.items
    )
    return {
        "id":      _deterministic_event_id(order_id),  # idempoten: 409 = sudah ada
        "summary": f"[UMKM] Pesanan {order.nama_pelanggan}",
        "description": (
            f"order_id:{order_id}\n"  # untuk idempoten lookup
            f"Pelanggan: {order.nama_pelanggan}\n"
            f"Items: {item_summary}\n"
            f"Catatan: {order.catatan or '—'}"
        ),
        "start": {"dateTime": start_dt.isoformat(), "timeZone": "Asia/Jakarta"},
        "end":   {"dateTime": end_dt.isoformat(),   "timeZone": "Asia/Jakarta"},
        "reminders": {
            "useDefault": False,
            "overrides": [
                {"method": "popup", "minutes": 60},
                {"method": "popup", "minutes": 1440},
            ],
        },
        # attendees sengaja tidak diisi — tidak kirim undangan ke pelanggan
    }


# ── Google API helper (injectable untuk testing) ─────────────────────────────

class _GoogleServices:
    """Wraps google-api-python-client untuk injectable testing."""

    def __init__(self, token_path: str, scopes: list):
        try:
            from google.oauth2.credentials import Credentials  # type: ignore
            from google.auth.transport.requests import Request  # type: ignore
            from googleapiclient.discovery import build  # type: ignore
        except ImportError:
            raise ImportError(
                "google-api-python-client dan google-auth-oauthlib belum terinstall.\n"
                "Jalankan: pip install google-api-python-client google-auth-oauthlib google-auth-httplib2"
            )

        if not os.path.exists(token_path):
            raise FileNotFoundError(
                f"token.json tidak ditemukan di: {token_path}\n"
                "Jalankan: python scripts/setup_google_auth.py"
            )

        creds = Credentials.from_authorized_user_file(token_path, scopes)
        # Refresh token jika expired
        if creds.expired and creds.refresh_token:
            creds.refresh(Request())
            with open(token_path, "w") as f:
                f.write(creds.to_json())

        self._docs = build("docs", "v1", credentials=creds)
        self._cal  = build("calendar", "v3", credentials=creds)

    def create_doc(self, title: str) -> str:
        """Create doc, return documentId."""
        doc = self._docs.documents().create(body={"title": title}).execute()
        return doc["documentId"]

    def insert_doc_content(self, doc_id: str, content: str) -> None:
        """Insert text content at index 1 of doc."""
        self._docs.documents().batchUpdate(
            documentId=doc_id,
            body={"requests": [
                {"insertText": {"location": {"index": 1}, "text": content}}
            ]},
        ).execute()

    def find_event_by_order_id(self, order_id: str, calendar_id: str = "primary") -> Optional[str]:
        """
        Search existing calendar event by order_id in description.
        Return event_id or None.
        """
        result = self._cal.events().list(
            calendarId=calendar_id,
            q=f"order_id:{order_id}",
            maxResults=5,
        ).execute()
        events = result.get("items", [])
        for evt in events:
            if f"order_id:{order_id}" in (evt.get("description") or ""):
                return evt["id"]
        return None

    def doc_has_content(self, doc_id: str, order_id: str) -> bool:
        """
        Cek apakah dokumen sudah berisi marker UMKM_ORDER_ID:<order_id>.
        True  = marker ditemukan → skip insert (idempoten saat response hilang).
        False = marker tidak ditemukan → insert diperlukan.

        PENTING: exception TIDAK ditangkap di sini.
        Jika GET gagal (network error, 403, 404), error dipropagasi ke caller
        agar insert TIDAK dilanjutkan dengan asumsi salah.
        Caller (commit_docs) menangkap error ini dan menyimpannya di errors["docs_content"].
        """
        doc = self._docs.documents().get(documentId=doc_id).execute()
        body_content = doc.get("body", {}).get("content", [])
        for element in body_content:
            para = element.get("paragraph", {})
            for pe in para.get("elements", []):
                text = pe.get("textRun", {}).get("content", "")
                if f"{_UMKM_MARKER_PREFIX}{order_id}" in text:
                    return True
        return False

    def create_event(self, event_body: dict, calendar_id: str = "primary") -> Tuple[str, str]:
        """
        Create event. Jika ID deterministik sudah ada (HTTP 409),
        fetch event existing dan kembalikan htmlLink asli (bukan raw eid URL).
        """
        try:
            from googleapiclient.errors import HttpError  # type: ignore
        except ImportError:
            HttpError = Exception  # type: ignore

        try:
            evt = self._cal.events().insert(
                calendarId=calendar_id, body=event_body
            ).execute()
            return evt["id"], evt.get("htmlLink", "")
        except Exception as e:
            # Deteksi HTTP 409 Conflict (event dengan ID ini sudah ada)
            status_code = getattr(e, "resp", {}).get("status", 0) if hasattr(e, "resp") else 0
            try:
                status_code = int(status_code)
            except (ValueError, TypeError):
                status_code = 0

            if status_code == 409 and event_body.get("id"):
                # Event sudah ada — ambil htmlLink asli, bukan bangun URL dari eid
                html_link = self.get_event_html_link(event_body["id"], calendar_id)
                return event_body["id"], html_link
            raise  # error lain — propagate

    def get_event_html_link(self, event_id: str, calendar_id: str = "primary") -> str:
        """
        Ambil htmlLink dari event yang sudah ada.
        Exception TIDAK ditangkap — propagasi ke caller.
        Caller wajib menangani error ini (jangan silent return "").
        """
        evt = self._cal.events().get(calendarId=calendar_id, eventId=event_id).execute()
        return evt.get("htmlLink", "")


