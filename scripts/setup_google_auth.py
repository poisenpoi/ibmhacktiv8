"""
scripts/setup_google_auth.py
─────────────────────────────
Setup OAuth Google Docs & Calendar untuk live mode.
Dijalankan SEKALI oleh user setelah menyiapkan credentials.json.

Jalankan:
  python scripts/setup_google_auth.py

Prasyarat:
  1. credentials.json ada di .secrets/credentials.json
     (Download dari Google Cloud Console → Credentials → Desktop OAuth Client)
  2. pip install google-api-python-client google-auth-oauthlib google-auth-httplib2

Output: .secrets/token.json  (JANGAN commit ke Git)
Generated by IBM Bob | Asisten Pesanan UMKM
"""
from __future__ import annotations
import io
import os
import sys
from pathlib import Path

# Windows console sering pakai cp1252/cp950 — paksa UTF-8 sebelum ada print emoji
if sys.stdout and hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
if sys.stderr and hasattr(sys.stderr, "reconfigure"):
    try:
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

_ROOT    = Path(__file__).parent.parent
_SECRETS = _ROOT / ".secrets"
_CREDS   = _SECRETS / "credentials.json"
_TOKEN   = _SECRETS / "token.json"

SCOPES = [
    "https://www.googleapis.com/auth/documents",
    "https://www.googleapis.com/auth/calendar.events",
    "https://www.googleapis.com/auth/drive.file",
]

def main():
    print("=" * 60)
    print("  Setup OAuth Google untuk Asisten Pesanan UMKM")
    print("=" * 60)

    # Cek credentials.json
    if not _CREDS.exists():
        print(f"""
❌ credentials.json tidak ditemukan di: {_CREDS}

Langkah untuk mendapatkannya:
  1. Buka https://console.cloud.google.com
  2. Pilih/buat project
  3. APIs & Services → Library → Enable:
       • Google Docs API
       • Google Calendar API
  4. APIs & Services → Credentials
       → + CREATE CREDENTIALS → OAuth 2.0 Client IDs
       → Application type: Desktop app
       → Name: Asisten Pesanan UMKM
       → CREATE → Download JSON
  5. Simpan file tersebut sebagai:
       {_CREDS}
  6. Jalankan kembali script ini.
""")
        sys.exit(1)

    # Cek library
    try:
        from google_auth_oauthlib.flow import InstalledAppFlow  # type: ignore
        from googleapiclient.discovery import build  # type: ignore
        from google.auth.transport.requests import Request  # type: ignore
        from google.oauth2.credentials import Credentials  # type: ignore
    except ImportError:
        print("""
❌ Library Google belum terinstall.

Jalankan:
  pip install google-api-python-client google-auth-oauthlib google-auth-httplib2
""")
        sys.exit(1)

    # Cek token existing
    creds = None
    if _TOKEN.exists():
        try:
            creds = Credentials.from_authorized_user_file(str(_TOKEN), SCOPES)
            if creds.valid:
                print(f"✅ Token sudah valid: {_TOKEN}")
                _test_apis(creds)
                return
            if creds.expired and creds.refresh_token:
                print("   Token expired — refresh...")
                creds.refresh(Request())
                _TOKEN.write_text(creds.to_json())
                print(f"✅ Token direfresh: {_TOKEN}")
                _test_apis(creds)
                return
        except Exception as e:
            print(f"   Token existing tidak valid ({e}), akan buat baru.")
            creds = None

    # OAuth flow baru
    print("""
Browser akan terbuka untuk login Google.
Pilih akun Google yang akan digunakan untuk menyimpan pesanan.
Grant permission untuk:
  - Google Docs (Create & edit documents)
  - Google Calendar (Create events)
  - Drive (Access files created by this app)
""")
    input("Tekan ENTER untuk membuka browser... ")

    flow = InstalledAppFlow.from_client_secrets_file(str(_CREDS), SCOPES)
    creds = flow.run_local_server(port=0)

    # Simpan token
    _SECRETS.mkdir(parents=True, exist_ok=True)
    _TOKEN.write_text(creds.to_json())
    print(f"\n✅ Token tersimpan: {_TOKEN}")
    print("   JANGAN commit file ini ke Git!\n")

    _test_apis(creds)

    print("""
Langkah berikutnya untuk mengaktifkan live mode:
  PowerShell: $env:UMKM_GOOGLE_LIVE = "1"
              $env:UMKM_GOOGLE_TOKEN = ".secrets/token.json"
  Atau isi bagian env di .bob/mcp.json (file .env tidak dibaca otomatis):
              UMKM_GOOGLE_LIVE=1
              UMKM_GOOGLE_TOKEN=.secrets/token.json
""")


def _test_apis(creds):
    """
    Test koneksi ke Google APIs — read-only, tidak membuat resource.

    CATATAN JUJUR:
      - Docs: hanya test apakah library bisa di-build dengan credentials.
        Tidak memanggil API endpoint nyata (documents.list tidak tersedia di Docs API v1).
        Status "OK" berarti token valid & library loaded, BUKAN berarti write permission tested.
      - Calendar: memanggil events().list() (read-only) untuk test koneksi nyata.
        Membutuhkan scope calendar.events.
    """
    from googleapiclient.discovery import build  # type: ignore

    print("\n   Testing Google Docs API (library load only — API call tidak dilakukan)...")
    try:
        svc = build("docs", "v1", credentials=creds)
        # documents() hanya build resource object — tidak memanggil API
        # Test write permission baru diketahui saat create doc pertama kali
        _ = svc.documents()
        print("   ✅ Google Docs API: library loaded, token valid (write belum ditest)")
    except Exception as e:
        print(f"   ❌ Google Docs API: {e}")

    print("   Testing Google Calendar API (events.list — real API call)...")
    try:
        cal = build("calendar", "v3", credentials=creds)
        # events().list() dengan calendarId primary adalah read-only test nyata
        # Berbeda dari calendarList (butuh scope berbeda)
        cal.events().list(calendarId="primary", maxResults=1).execute()
        print("   ✅ Google Calendar API: OK (events.list berhasil)")
    except Exception as e:
        print(f"   ❌ Google Calendar API: {e}")


if __name__ == "__main__":
    main()
